"""Run by build.py. Generate assets/theme-dark.css: every rule from styles.css + classic.css that paints a
light surface or dark text gets a dark-theme counterpart under html[data-theme="dark"]."""
import re, sys, os
root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(root + '/assets/styles.css').read() + '\n' + open(root + '/assets/classic.css').read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)

WHITE_BG = re.compile(r'^(#fff(fff)?|white|oklch\(1 0 0 / (6\d|7\d|8\d|9\d)%\)|oklch\(0\.9[6-9][^)]*\))$')
INK_BG = re.compile(r'^var\(--ink(-soft|-2)?\)$')
DARK_TXT = re.compile(r'^oklch\(0\.(1\d|2\d|3\d)\d* [^)]*\)$')

def blocks(css):
    """yield (media_prefix, selector, body) for flat rules, one level of @media/@supports."""
    i = 0
    n = len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: break
        head = css[i:j].strip()
        if head.startswith('@media') or head.startswith('@supports'):
            depth, k = 1, j + 1
            while depth and k < n:
                if css[k] == '{': depth += 1
                elif css[k] == '}': depth -= 1
                k += 1
            inner = css[j + 1:k - 1]
            for _, s, b in blocks(inner):
                yield head, s, b
            i = k
        elif head.startswith('@keyframes') or head.startswith('@font-face'):
            depth, k = 1, j + 1
            while depth and k < n:
                if css[k] == '{': depth += 1
                elif css[k] == '}': depth -= 1
                k += 1
            i = k
        else:
            k = css.find('}', j)
            yield None, head, css[j + 1:k]
            i = k + 1

SKIP = {'body', '.hero', '.page-hero', '.ba-line', '.ba-handle', '.marquee', '.blueprint-grid', 'html'}
out = {}
order = []
for media, sel, body in blocks(src):
    decls = []
    for d in body.split(';'):
        if ':' not in d: continue
        p, v = d.split(':', 1)
        p, v = p.strip(), v.strip()
        imp = ' !important' if '!important' in v else ''
        v0 = v.replace('!important', '').strip()
        if p in ('background', 'background-color'):
            if WHITE_BG.match(v0):
                decls.append(f'{p}: var(--card){imp}')
            elif INK_BG.match(v0):
                decls.append(f'{p}: var(--night){imp}')
        elif p == 'color' and DARK_TXT.match(v0):
            decls.append(f'color: var(--ink-soft){imp}')
    if not decls: continue
    parts = [x.strip() for x in sel.split(',') if x.strip() and x.strip() not in SKIP]
    if not parts: continue
    sels = ', '.join('html[data-theme="dark"] ' + x for x in parts)
    key = (media, sels)
    if key not in out:
        out[key] = []
        order.append(key)
    out[key] += decls

lines = ['/* Generated by tools/gen_dark.py — do not edit by hand; tweaks go in classic.css (dark section). */']
for media, sels in order:
    body = '\n'.join(f'  {d};' for d in dict.fromkeys(out[(media, sels)]))
    rule = f'{sels} {{\n{body}\n}}'
    if media:
        rule = media + ' {\n' + rule + '\n}'
    lines.append(rule)
lines.append(open(root + '/build/partials/dark-manual.css').read())
open(root + '/assets/theme-dark.css', 'w').write('\n'.join(lines) + '\n')
print(len(order), 'rules')
